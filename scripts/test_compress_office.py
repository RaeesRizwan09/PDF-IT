#!/usr/bin/env python3
"""
Live e2e test of pdf_compress + office_to_pdf over the remote MCP endpoint.

Locally builds (1) an image-heavy PDF and (2) a PPTX deck, uploads both to
Azure Blob via the az CLI, then calls the new MCP tools with those URLs and
verifies the returned PDFs.

Usage: python3 scripts/test_compress_office.py <mcp-endpoint-url>
"""

from __future__ import annotations

import asyncio
import io
import json
import os
import random
import subprocess
import sys
import tempfile
from urllib.request import urlopen

from mcp import ClientSession
from mcp.client.streamable_http import streamable_http_client
from pypdf import PdfReader

RG = "rg-html2pdf-4821"
STG = "sthtml2pdf4821"
CONTAINER = "generated-pdfs"


def az(*args: str) -> str:
    return subprocess.run(["az", *args], check=True, capture_output=True,
                          text=True).stdout.strip()


def upload_blob(path: str, name: str) -> str:
    conn = az("storage", "account", "show-connection-string",
              "-n", STG, "-g", RG, "-o", "tsv", "--query", "connectionString")
    az("storage", "blob", "upload", "--connection-string", conn,
       "--container-name", CONTAINER, "--name", name,
       "--file", path, "--overwrite", "-o", "none")
    expiry = subprocess.run(
        ["date", "-u", "-d", "+1 day", "+%Y-%m-%dT%H:%M:%SZ"],
        capture_output=True, text=True).stdout.strip()
    sas = az("storage", "blob", "generate-sas", "--connection-string", conn,
             "--container-name", CONTAINER, "--name", name,
             "--permissions", "r", "--expiry", expiry, "-o", "tsv")
    return (f"https://{STG}.blob.core.windows.net/{CONTAINER}/{name}?{sas}")


def make_image_pdf(path: str) -> int:
    from PIL import Image
    from reportlab.pdfgen import canvas
    random.seed(7)
    img = Image.new("RGB", (1024, 1024))
    img.putdata([(random.randrange(256), random.randrange(256),
                  random.randrange(256)) for _ in range(1024 * 1024)])
    jp = path.replace(".pdf", ".jpg")
    img.save(jp, format="JPEG", quality=90)
    c = canvas.Canvas(path, pagesize=(595, 842))
    c.drawImage(jp, 50, 300, width=495, height=500)
    c.drawCentredString(297, 700, "quarterly figures and noisy chart")
    c.showPage()
    c.save()
    os.unlink(jp)
    return os.path.getsize(path)


def make_pptx(path: str) -> int:
    from pptx import Presentation
    from pptx.util import Inches, Pt
    prs = Presentation()
    for i, title in enumerate(["Azure MCP Rocks", "Cost Overview",
                               "Next Steps"], 1):
        slide = prs.slides.add_slide(prs.slide_layouts[1])
        slide.shapes.title.text = title
        slide.placeholders[1].text = (f"Slide {i} content — this deck was "
                                      "generated by the smoke test.")
        slide.notes_slide.notes_text_frame.text = "auto-generated"
    prs.save(path)
    return os.path.getsize(path)


def download(url: str) -> bytes:
    return urlopen(url, timeout=60).read()


async def main(server_url: str) -> int:
    td = tempfile.mkdtemp()
    pdf_src = os.path.join(td, "heavy.pdf")
    pptx_src = os.path.join(td, "deck.pptx")
    pdf_size = make_image_pdf(pdf_src)
    pptx_size = make_pptx(pptx_src)
    print(f"built assets: heavy.pdf={pdf_size}B deck.pptx={pptx_size}B — uploading to Blob...")
    pdf_url = upload_blob(pdf_src, "smoke/heavy.pdf")
    pptx_url = upload_blob(pptx_src, "smoke/deck.pptx")
    print("  uploaded:", pdf_url.split("?")[0])
    print("  uploaded:", pptx_url.split("?")[0])

    async with streamable_http_client(server_url) as streams:
        read, write = streams[0], streams[1]
        async with ClientSession(read, write) as session:
            await session.initialize()

            async def call(name, args) -> dict:
                res = await session.call_tool(name, args)
                return json.loads(res.content[0].text)

            print("\npdf_compress: light / medium / strong ...")
            prev = pdf_size
            for level in ("light", "medium", "strong"):
                r = await call("pdf_compress",
                               {"pdf_url": pdf_url, "level": level,
                                "filename": f"heavy-{level}.pdf"})
                assert r.get("ok") and r.get("pdf_url"), r
                raw = download(r["pdf_url"])
                assert raw[:4] == b"%PDF", "not a PDF"
                size, pct = r["bytes"], r["saved_pct"]
                print(f"  {level:7s}: {size:>7} B  ({pct}% off  "
                      f"orig {pdf_size} B)  fields={ {k: r[k] for k in ()} }")
                assert size <= prev, f"{level} did not shrink"
                prev = size
                if level == "light":
                    assert len(PdfReader(io.BytesIO(raw)).pages) == 1

            print("office_to_pdf (PPTX) ...")
            o = await call("office_to_pdf",
                           {"input_url": pptx_url,
                            "filename": "deck.pptx"})
            assert o.get("ok") and o.get("pdf_url"), o
            raw = download(o["pdf_url"])
            assert raw[:4] == b"%PDF", "office_to_pdf did not return a PDF"
            r = PdfReader(io.BytesIO(raw))
            assert len(r.pages) == 3, f"expected 3 slides, got {len(r.pages)}"
            assert "Azure" in r.pages[0].extract_text(), r.pages[0].extract_text()
            print(f"  synced 3 slides → {o['bytes']} B PDF, text OK "
                  f"(input_type={o ['input_type']})")

            print("office_to_pdf: bad type rejected ...")
            bad = await call("office_to_pdf", {"input_url": pdf_url})
            assert not bad.get("ok") and ".pdf" in bad.get("error", ""), bad

            print("\nALL COMPRESS/OFFICE LIVE TESTS PASSED")
    return 0


if __name__ == "__main__":
    if len(sys.argv) != 2:
        sys.exit(f"usage: {sys.argv[0]} <mcp-endpoint-url>")
    sys.exit(asyncio.run(main(sys.argv[1])))
